// Generates docs/m0/rule-traces.md: plain-English play-by-plays for the M0 checkpoint.
// Run with `npm run trace`. Deterministic: the same seed always produces the same file.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  applySessionAction,
  bid,
  cardLabel,
  declarerTarget,
  defenderTarget,
  hcp,
  newSession,
  next,
  partner,
  PASS,
  seatsFrom,
  seatToAct,
  sideOf,
  suitSymbol,
  tableView,
  trumpSuit,
  type Call,
  type CompletedTrick,
  type PairId,
  type ProfileId,
  type Seat,
  type SessionAction,
  type SessionState,
  type Strain,
} from '../src';
import { botCard } from '../src/bots';

const NAMES: Record<ProfileId, string> = { darren: 'Darren', adrian: 'Adrian', ryan: 'Ryan', kim: 'Kim' };
const SEED = 'da4cb41d9e5a2c1f0b7d3e8a6c4f2b19';

const out: string[] = [];
const say = (line = '') => out.push(line);

let s = newSession({
  profiles: ['darren', 'adrian', 'ryan', 'kim'],
  usualPartner: { darren: 'kim', kim: 'darren', adrian: 'ryan', ryan: 'adrian' },
  seed: SEED,
});

function apply(action: SessionAction): void {
  const result = applySessionAction(s, action);
  if (!result.ok) throw new Error(`${action.type}: ${result.error.code} ${result.error.message}`);
  s = result.state;
}

/** Read through a function so TypeScript doesn't keep a stale narrowing after `apply`. */
const dealPhase = () => s.deal?.phase;
const nameAt = (seat: Seat) => NAMES[s.seating![seat]]!;
const pairName = (pair: PairId) => s.pairs![pair].map((p) => NAMES[p]).join(' & ');
const strainLabel = (strain: Strain) => (strain === 'NT' ? 'NT' : suitSymbol(strain));
const ordinal = (n: number) => `${n}${n % 10 === 1 && n !== 11 ? 'st' : n % 10 === 2 && n !== 12 ? 'nd' : n % 10 === 3 && n !== 13 ? 'rd' : 'th'}`;
const callLabel = (call: Call) => (call.type === 'pass' ? 'Pass' : `${call.level}${strainLabel(call.strain)}`);

// ---------------------------------------------------------------------------------------------

interface Scenario {
  title: string;
  why: string;
  calls: Call[];
  /** Extra actions to send after a given number of completed tricks. */
  afterTrick?: Record<number, (st: SessionState) => SessionAction[]>;
  /** Who taps "Play on" at the clinch, or null to let the 5 s window close. */
  playOn: (st: SessionState) => ProfileId | null;
  narrateAfterTrick?: Record<number, string>;
}

function header(): void {
  say('# M0 checkpoint: rule traces');
  say();
  say('Generated by `npm run trace` from the real rules engine, using a fixed seed so the file is reproducible.');
  say('Cards are played by a simple practice bot, so **judge the rules, not the bridge**.');
  say();
  say('**For each deal, please check:** who deals, the bidding order, who becomes declarer, who leads first,');
  say('the play order, who wins each trick and why, when the deal is settled, and the score.');
  say('Anything that does not match how the four of you play is a bug in the engine.');
  say();
}

function startNight(): void {
  apply({ type: 'start' });
  const captain = s.captain!;
  say('## Start of the night');
  say();
  say(`1. **Captain draw:** ${NAMES[captain]} is drawn as captain.`);
  say(`2. **Partner pick:** ${NAMES[s.suggestedPartner!]} (${NAMES[captain]}'s usual partner) is pre-selected, and ${NAMES[captain]} confirms.`);
  apply({ type: 'pickPartner', by: captain, partner: s.suggestedPartner! });
  say(`3. **Pairs for the whole night:** ${pairName('A')} vs ${pairName('B')}.`);
  const order = seatsFrom(0).map(nameAt);
  say(`4. **Seating, counter-clockwise:** ${order.join(' → ')} → (back to ${order[0]}).`);
  say(`   In this list, **each player's right-hand neighbour is the next name**, so this is also the order of bidding and play.`);
  say(`   Partners sit opposite: ${pairName('A')}, and ${pairName('B')}.`);
  say(`5. **First dealer** (random): ${nameAt(s.dealer!)}.`);
  say();
}

function handsTable(): void {
  const deal = s.deal!;
  say('| Player | Hand | HCP |');
  say('|---|---|---|');
  for (const seat of seatsFrom(deal.dealer)) {
    const hand = deal.originalHands[seat];
    const bySuit = (['S', 'H', 'D', 'C'] as const)
      .map((suit) => `${suitSymbol(suit)} ${hand.filter((c) => c.suit === suit).map((c) => cardLabel(c).slice(1)).join(' ') || '—'}`)
      .join(' &nbsp; ');
    say(`| ${nameAt(seat)} | ${bySuit} | ${hcp(hand)} |`);
  }
  say();
}

function why(trick: CompletedTrick, strain: Strain): string {
  const trump = trumpSuit(strain);
  const led = trick.cards[0]!.card.suit;
  const w = trick.winningCard;
  if (trump && w.suit === trump && led !== trump) {
    const trumps = trick.cards.filter((p) => p.card.suit === trump).length;
    return trumps > 1 ? `highest trump (${suitSymbol(trump)})` : `the only trump (${suitSymbol(trump)} are trumps)`;
  }
  return `highest ${suitSymbol(led)}, the suit led`;
}

function runDeal(n: number, sc: Scenario): void {
  const dealer = s.dealer!;
  say(`## Deal ${n}: ${sc.title}`);
  say();
  say(`*What this shows: ${sc.why}*`);
  say();
  say(`**Dealer:** ${nameAt(dealer)}. Bidding starts with the dealer and goes counter-clockwise: ${seatsFrom(dealer).map(nameAt).join(' → ')}.`);
  say();
  handsTable();

  const dealNumber = s.dealNumber;
  say('**Bidding**');
  say();
  for (const c of sc.calls) {
    const seat = seatToAct(s.deal!)!;
    say(`- ${nameAt(seat)}: ${callLabel(c)}`);
    apply({ type: 'deal', by: s.seating![seat], action: { type: 'call', call: c } });
  }
  say();

  // A pass-out redeals immediately, so the session has already moved to the next deal.
  if (s.dealNumber !== dealNumber) {
    say(`**All four passed.** The hand is thrown in and redealt. The deal passes to the dealer's right: **${nameAt(s.dealer!)}** deals next.`);
    say();
    return;
  }
  if (s.deal!.phase === 'auction') throw new Error('Scenario auction did not finish');

  const deal = s.deal!;
  const contract = deal.contract!;
  const decl = contract.declarer;
  const declPair = [decl, partner(decl)].map(nameAt).join(' & ');
  const defPair = [next(decl), partner(next(decl))].map(nameAt).join(' & ');
  const firstToName = deal.auction.calls.find(
    (e) => e.call.type === 'bid' && e.call.strain === contract.strain && (e.seat === decl || e.seat === partner(decl)),
  )!;
  say(`**Contract:** ${contract.level}${strainLabel(contract.strain)} by **${nameAt(decl)}**, who made the final bid (house rule R4).` +
    (firstToName.seat !== decl ? ` Note that ${nameAt(firstToName.seat)} named ${strainLabel(contract.strain)} first; under standard rules ${nameAt(firstToName.seat)} would have declared.` : ''));
  say();
  say(`- Declarers (${declPair}) need **${declarerTarget(contract.level)}** tricks to make it.`);
  say(`- Defenders (${defPair}) need **${defenderTarget(contract.level)}** tricks to set it.`);
  say(`- **Opening lead:** ${nameAt(next(decl))}, on ${nameAt(decl)}'s right. Every hand stays hidden (no dummy).`);
  say();
  say('**Play** (counter-clockwise from the leader; the trick winner leads next)');
  say();
  say('| # | Cards in play order | Winner | Why | Declarers | Defenders |');
  say('|---|---|---|---|---|---|');

  const notes: string[] = [];
  let reported = 0;
  const flushTricks = () => {
    const d = s.deal!;
    while (reported < d.tricks.length) {
      const t = d.tricks[reported]!;
      reported++;
      const declWon = d.tricks.slice(0, reported).filter((x) => sideOf(x.winner, contract) === 'declarers').length;
      const cards = t.cards.map((p) => `${nameAt(p.seat)} ${cardLabel(p.card)}`).join(' · ');
      const mark = d.clinch && d.clinch.trickNumber === reported ? ' 🏁' : '';
      say(`| ${reported}${mark} | ${cards} | ${nameAt(t.winner)} | ${why(t, contract.strain)} | ${declWon}/${declarerTarget(contract.level)} | ${reported - declWon}/${defenderTarget(contract.level)} |`);
      const narrate = sc.narrateAfterTrick?.[reported];
      if (narrate) notes.push(`After trick ${reported}: ${narrate}`);
    }
  };

  const handled = new Set<number>();
  while (s.deal && s.deal.phase === 'play') {
    const done = s.deal.tricks.length;
    if (s.deal.currentTrick!.cards.length === 0 && sc.afterTrick?.[done] && !handled.has(done)) {
      handled.add(done);
      flushTricks();
      for (const a of sc.afterTrick[done]!(s)) apply(a);
      if (!s.deal || s.deal.phase !== 'play') break;
    }
    const seat = seatToAct(s.deal)!;
    apply({ type: 'deal', by: s.seating![seat], action: { type: 'play', card: botCard(tableView(s, s.seating![seat]).deal!, seat, s.deal!.tricks) } });
    if (dealPhase() === 'awaitingPlayOn') {
      flushTricks();
      const who = sc.playOn(s);
      const c = s.deal!.clinch!;
      notes.push(
        `🏁 **Settled on trick ${c.trickNumber}:** ${nameAt(c.seat)}'s ${cardLabel(c.card)} wins it, giving the ${c.side} their ${ordinal(c.side === 'declarers' ? declarerTarget(contract.level) : defenderTarget(contract.level))} trick. "Play it out?" appears.`,
      );
      if (who) {
        notes.push(`${NAMES[who]} taps **Play on**, so play continues to trick 13 (the result is already fixed).`);
        apply({ type: 'deal', by: who, action: { type: 'playOn' } });
      } else {
        notes.push('Nobody taps **Play on** within 5 seconds, so the deal ends here.');
        apply({ type: 'dealTimer', action: 'endAtClinch' });
      }
    }
  }
  flushTricks();
  say();
  for (const note of notes) say(`- ${note}`);

  const record = s.records[s.records.length - 1]!;
  const r = record.result!;
  const verdict = r.reason === 'conceded' ? 'CONCEDED' : r.winner === 'declarers' ? 'MADE' : 'SET';
  say(`- **Result: ${verdict}.** ${pairName(record.winningPair!)} +1 win.` +
    (r.overUnder === null ? ' Over/undertricks not recorded (not played out).' :
      ` Played out: declarers took ${r.declarerTricks}, so ${r.overUnder >= 0 ? `+${r.overUnder} overtrick${r.overUnder === 1 ? '' : 's'}` : `${-r.overUnder} down`} (stats only).`));
  say(`- **Night so far:** ${pairName('A')} ${s.wins.A} · ${pairName('B')} ${s.wins.B}`);
  say(`- All four tap "Next deal" after the 4-hand reveal. The deal passes to ${nameAt(dealer)}'s right: **${nameAt(next(dealer))}** deals next.`);
  say();
  for (const p of ['darren', 'adrian', 'ryan', 'kim']) apply({ type: 'readyForNext', by: p });
}

// ---------------------------------------------------------------------------------------------

header();
startNight();

const seatProfile = (st: SessionState, seat: Seat) => st.seating![seat];

runDeal(1, {
  title: 'Partner raises to game, ends at the clinch',
  why: 'the final bidder declares, the opening lead comes from declarer’s right, play is counter-clockwise, and the deal ends at the clinch.',
  calls: [bid(1, 'NT'), PASS, bid(3, 'NT'), PASS, PASS, PASS],
  playOn: () => null,
});

runDeal(2, {
  title: 'Pass-out',
  why: 'four passes throw the hand in, and the deal moves to the dealer’s right.',
  calls: [PASS, PASS, PASS, PASS],
  playOn: () => null,
});

runDeal(3, {
  title: 'The raiser declares; someone plays it out',
  why: 'house rule R4 (final bidder declares even when partner named the suit first), and a defender choosing "Play on" so over/undertricks are recorded.',
  calls: [bid(1, 'H'), PASS, bid(2, 'H'), PASS, PASS, PASS],
  playOn: (st) => seatProfile(st, next(st.deal!.contract!.declarer)),
});

runDeal(4, {
  title: 'Concessions: one declined, one accepted',
  why: 'a concession needs the proposer’s partner to accept, and an accepted concession gives the deal to the other side.',
  // A 2-level contract can't be settled before trick 6, so both proposals happen while it is open.
  calls: [bid(1, 'S'), bid(2, 'D'), bid(2, 'S'), PASS, PASS, PASS],
  afterTrick: {
    1: (st) => {
      const decl = st.deal!.contract!.declarer;
      return [
        { type: 'deal', by: seatProfile(st, decl), action: { type: 'proposeConcession' } },
        { type: 'deal', by: seatProfile(st, partner(decl)), action: { type: 'declineConcession' } },
      ];
    },
    3: (st) => {
      const def = next(st.deal!.contract!.declarer);
      return [
        { type: 'deal', by: seatProfile(st, def), action: { type: 'proposeConcession' } },
        { type: 'deal', by: seatProfile(st, partner(def)), action: { type: 'acceptConcession' } },
      ];
    },
  },
  narrateAfterTrick: {
    1: 'declarer proposes conceding the rest; declarer’s partner **declines**, so play continues with nothing changed.',
    3: 'the defender on declarer’s right proposes conceding; their partner **accepts**, so the deal ends and the declarers win it.',
  },
  playOn: () => null,
});

runDeal(5, {
  title: 'An ambitious slam',
  why: 'a 6-level contract where the defenders need only 2 tricks, and how the clinch works for the defending side.',
  calls: [PASS, bid(1, 'C'), PASS, bid(1, 'H'), PASS, bid(2, 'NT'), PASS, bid(6, 'NT'), PASS, PASS, PASS],
  playOn: () => null,
});

say('## End of the night');
say();
for (const p of ['darren', 'adrian', 'ryan', 'kim']) apply({ type: 'voteEndNight', by: p });
const final = s.final!;
say('All four vote to end the night (a deal had just been dealt, so it is discarded and does not count).');
say();
say(`**Final:** ${pairName('A')} ${final.wins.A} · ${pairName('B')} ${final.wins.B} → ` +
  (final.winner === 'tie' ? '**a tie** (ties are allowed).' : `**${pairName(final.winner)} win the night.**`));
say();

const target = join(dirname(fileURLToPath(import.meta.url)), '../../../docs/m0/rule-traces.md');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
